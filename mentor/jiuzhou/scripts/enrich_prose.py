def main() -> None:
    # ADR 0001：只覆盖 PROSE 表里的手写稿；禁止再 import 灌水垫句。
    data = json.loads(ATLAS.read_text(encoding="utf-8"))
    missing = [e["id"] for e in data["events"] if e["id"] not in PROSE]
    if missing:
        raise SystemExit(f"missing prose for: {missing}")
    for e in data["events"]:
        summary, impact = PROSE[e["id"]]
        e["summary"] = summary
        e["impact"] = impact
    ATLAS.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    lengths = [(e["id"], len(e["summary"]), len(e["impact"])) for e in data["events"]]
    short = [l for l in lengths if l[1] < 60 or l[2] < 60]
    print(
        f"enriched {len(PROSE)} events; "
        f"min summary={min(l[1] for l in lengths)} impact={min(l[2] for l in lengths)}; "
        f"avg summary={sum(l[1] for l in lengths)/len(lengths):.0f} "
        f"impact={sum(l[2] for l in lengths)/len(lengths):.0f}"
    )
    if short:
        raise SystemExit(f"still under 60 chars: {short}")



if __name__ == "__main__":
    main()
